"""Builds web/countries.js: national outlines (the union of each country's regions) for the map's border line
and the flag labels. Run after tools/rebuild_regions.py. Needs shapely.
"""
import io, json, os, re

from shapely.geometry import Polygon, MultiPolygon
from shapely.ops import unary_union

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
hubs = {k: v for k, v in json.load(io.open(os.path.join(HERE, "hubs.json"), encoding="utf-8")).items() if not k.startswith("_")}
src = io.open(os.path.join(ROOT, "web", "regions.js"), encoding="utf-8").read()
REG = json.loads(re.search(r"window\.REGIONS = (\{.*?\});\n", src, re.S).group(1))
META = {"NL": {"name": "Netherlands", "label": [52.98, 6.02]}, "BE": {"name": "Belgium", "label": [50.02, 5.18]},
        "DE": {"name": "Germany", "label": [51.15, 10.3]}, "LU": {"name": "Luxembourg", "label": [49.80, 6.10]},
        "FR": {"name": "France", "label": [46.9, 2.6]}, "DK": {"name": "Denmark", "label": [56.25, 9.2]},
        "SE": {"name": "Sweden", "label": [61.2, 14.9]}, "CH": {"name": "Switzerland", "label": [46.75, 8.2]},
        "TR": {"name": "Türkiye", "label": [39.1, 34.6]},
        "CY": {"name": "Cyprus", "label": [35.05, 33.2]},
        "EL": {"name": "Greece", "label": [39.3, 22.0]}}

out = {}
for cc in sorted({v["country"] for v in hubs.values()}):
    polys = []
    for h, rings in REG.items():
        if hubs.get(h, {}).get("country") != cc:
            continue
        for poly in rings:
            polys.append(Polygon([(p[1], p[0]) for p in poly[0]], [[(p[1], p[0]) for p in hole] for hole in poly[1:]]))
    u = unary_union([p.buffer(0.002) for p in polys]).buffer(-0.002).simplify(0.002, preserve_topology=True)
    parts = list(u.geoms) if isinstance(u, MultiPolygon) else [u]
    lines = []
    for p in parts:
        if p.area < 3e-4:
            continue
        lines.append([[round(y, 4), round(x, 4)] for x, y in p.exterior.coords])
    out[cc] = {"name": META[cc]["name"], "label": META[cc]["label"], "outline": lines}

with io.open(os.path.join(ROOT, "web", "countries.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/build_countries.py: national outlines (union of each country's regions) and flag label points.\n"
            "window.COUNTRIES = " + json.dumps(out, separators=(",", ":")) + ";\n")
print({k: (len(v["outline"]), sum(len(l) for l in v["outline"])) for k, v in out.items()})
