"""Moves every quest into the region whose outline (web/regions.js) contains it, creating region files for
new hubs from tools/hubs.json. Progress is preserved: web/moved.js maps old quest keys to new ones and the
app migrates saved progress and photos on start.

Usage (needs shapely): python tools/reassign_quests.py
"""
import glob, io, json, math, os, re, sys

from shapely.geometry import Point, Polygon, MultiPolygon

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import regions_io as R

hubs = {k: v for k, v in json.load(io.open(os.path.join(HERE, "hubs.json"), encoding="utf-8")).items() if not k.startswith("_")}
src = io.open(os.path.join(ROOT, "web", "regions.js"), encoding="utf-8").read()
REG = json.loads(re.search(r"window\.REGIONS = (\{.*?\});\n", src, re.S).group(1))
polys = {h: MultiPolygon([Polygon([(p[1], p[0]) for p in poly[0]], [[(p[1], p[0]) for p in hole] for hole in poly[1:]]) for poly in rings])
         for h, rings in REG.items()}
ORDER = ["amsterdam", "rotterdam", "denhaag", "utrecht", "eindhoven", "denbosch", "breda", "arnhem", "maastricht",
         "zwolle", "enschede", "groningen", "leeuwarden", "middelburg",
         "brussel", "antwerpen", "gent", "brugge", "luik", "leuven", "mons", "hasselt", "namur",
         "luxembourg", "aachen", "koeln", "duesseldorf", "trier"]
COUNTRY_NAME = {"NL": "Netherlands", "BE": "Belgium", "DE": "Germany", "LU": "Luxembourg"}

cities = {}
for p in glob.glob(os.path.join(ROOT, "web", "cities", "*.js")):
    c = R.load(p); cities[c["id"]] = c
for h, v in hubs.items():
    if v.get("subtitle") and h in cities:
        cities[h]["subtitle"] = v["subtitle"]
    if h not in cities and v.get("new"):
        n = v["new"]
        lats = [p[0] for p in v["points"]]; lngs = [p[1] for p in v["points"]]
        cities[h] = {"id": h, "name": n["name"], "subtitle": n["subtitle"], "country": COUNTRY_NAME[v["country"]],
                     "levels": n["levels"], "areas": {k: a["label"] for k, a in n["areas"].items()},
                     "bounds": [[round(min(lats) - 0.03, 3), round(min(lngs) - 0.05, 3)], [round(max(lats) + 0.03, 3), round(max(lngs) + 0.05, 3)]],
                     "coords": {}, "areaBadges": {k: {"icon": a["icon"], "name": a["badge"]} for k, a in n["areas"].items()}, "quests": []}


def km(a, b):
    return math.hypot((a[0] - b[0]) * 111.3, (a[1] - b[1]) * 111.3 * math.cos(math.radians(a[0])))


def area_in(target, ll):
    n = hubs[target].get("new")
    if not n:
        return "cevre"
    best = None
    for k, a in n["areas"].items():
        if "center" in a and km(ll, a["center"]) <= a["km"] and (best is None or km(ll, a["center"]) < best[1]):
            best = (k, km(ll, a["center"]))
    return best[0] if best else "cevre"


moved_path = os.path.join(ROOT, "web", "moved.js")
moved = {}
if os.path.exists(moved_path):
    moved = json.loads(re.search(r"window\.MOVED = (\{.*?\});", io.open(moved_path, encoding="utf-8").read(), re.S).group(1))

moves = []
for cid in list(cities):
    c = cities[cid]
    country = hubs[cid]["country"]
    for q in list(c["quests"]):
        ll = c["coords"][q["id"]]
        pt = Point(ll[1], ll[0])
        inside = [h for h, mp in polys.items() if hubs[h]["country"] == country and mp.contains(pt)]
        target = inside[0] if inside else min((h for h in polys if hubs[h]["country"] == country), key=lambda h: polys[h].distance(pt))
        if target == cid:
            continue
        if target not in cities:  # that region has no quests yet: leave the quest where it is
            print("  stays: %s/%s lies in %s, which has no quests yet" % (cid, q["id"], target))
            continue
        t = cities[target]
        nid, i = q["id"], 2
        while nid in t["coords"]:
            nid = "%s%d" % (q["id"], i); i += 1
        q2 = dict(q, id=nid, area=q["area"] if (q["area"] != "cevre" and q["area"] in t["areas"] and not hubs[target].get("new")) else area_in(target, ll))
        if not hubs[target].get("new") and q2["area"] not in t["areas"]:
            q2["area"] = "cevre"
        c["quests"].remove(q); del c["coords"][q["id"]]
        t["quests"].append(q2); t["coords"][nid] = ll
        old, new = "%s/%s" % (cid, q["id"]), "%s/%s" % (target, nid)
        for k, v in list(moved.items()):  # keep chains short
            if v == old: moved[k] = new
        moved[old] = new
        moves.append((old, new, q["title"]))

moved = {k: v for k, v in moved.items() if k != v}
for cid, c in cities.items():
    R.dump(os.path.join(ROOT, "web", "cities", cid + ".js"), c)
with io.open(moved_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/reassign_quests.py: quests that moved to another region (old key -> new key).\n"
            "// The app moves saved progress and photos along on start.\n"
            "window.MOVED = " + json.dumps(moved, ensure_ascii=False, indent=0, sort_keys=True) + ";\n")

# Keep index.html and sw.js in sync with the region list.
ids = [i for i in ORDER if i in cities] + sorted(i for i in cities if i not in ORDER)
p = os.path.join(ROOT, "web", "index.html"); s = io.open(p, encoding="utf-8").read()
tags = "".join('  <script src="cities/%s.js"></script>\n' % i for i in ids)
s = re.sub(r'(  <script src="cities/[a-z]+\.js"></script>\n)+', tags, s)
if "moved.js" not in s:
    s = s.replace('  <script src="regions.js"></script>\n', '  <script src="regions.js"></script>\n  <script src="moved.js"></script>\n')
io.open(p, "w", encoding="utf-8", newline="\n").write(s)
p = os.path.join(ROOT, "web", "sw.js"); s = io.open(p, encoding="utf-8").read()
s = re.sub(r'("cities/[a-z]+\.js", )+', "".join('"cities/%s.js", ' % i for i in ids), s)
if '"moved.js"' not in s:
    s = s.replace('"regions.js", ', '"regions.js", "moved.js", ')
s = re.sub(r'citydiscovery-v(\d+)', lambda m: "citydiscovery-v%d" % (int(m.group(1)) + 1), s)
io.open(p, "w", encoding="utf-8", newline="\n").write(s)

print("moved", len(moves))
for o, n, t in moves:
    print("  %-28s -> %-28s %s" % (o, n, t[:50]))
print({i: len(cities[i]["quests"]) for i in ids})
